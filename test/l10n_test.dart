Map<String, dynamic> _arb(String lang) =>
    jsonDecode(File('lib/l10n/app_$lang.arb').readAsStringSync()) as Map<String, dynamic>;

/// Message keys of a translation file (not "@@locale" nor "@key" notes).
Map<String, String> _messages(String lang) => {
      for (final e in _arb(lang).entries)
        if (!e.key.startsWith('@')) e.key: e.value as String,
    };

/// Placeholder names in a message, e.g. {count} and the plural's count.
Set<String> _placeholders(String msg) => RegExp(r'\{(\w+)[,}]').allMatches(msg).map((m) => m.group(1)!).toSet();

Transcript _tr({bool auto = true, bool translated = false}) => Transcript(
      videoId: 'dQw4w9WgXcQ',
      title: 'Rocket landing',
      channel: 'Space Channel',
      languageCode: 'en',
      languageName: 'English',
      isAutoGenerated: auto,
      isTranslated: translated,
      segments: const [Segment(0, 2000, 'Welcome back'), Segment(61000, 2000, 'Thanks for watching')],
    );

void main() {
  group('ticket 01: language of the app', () {
    test('D-27: Portuguese of any country → Portuguese; any other → English', () {
      String r(List<Locale>? l) => resolveAppLocale(l).languageCode;
      expect(r(const [Locale('en')]), 'en');
      expect(r(const [Locale('en', 'GB')]), 'en');
      expect(r(const [Locale('es')]), 'en');
      expect(r(const [Locale('ja')]), 'en');
      expect(r(const [Locale('xx')]), 'en', reason: 'code with no support');
      expect(r(const [Locale('pt')]), 'pt');
      expect(r(const [Locale('pt', 'BR')]), 'pt');
      expect(r(const [Locale('pt', 'PT')]), 'pt');
      expect(r(const []), 'en');
      expect(r(null), 'en');
      // Only the first language counts (on Android 13+ that is the app's own).
      expect(r(const [Locale('es'), Locale('pt', 'BR')]), 'en');
      expect(r(const [Locale('pt', 'BR'), Locale('en')]), 'pt');
    });

    test('the app speaks exactly English and Portuguese', () {
      expect(appLocales.map((l) => l.languageCode), ['en', 'pt']);
      expect(AppLocalizations.supportedLocales.map((l) => l.languageCode).toSet(), {'en', 'pt'});
      expect(_arb('en')['@@locale'], 'en');
      expect(_arb('pt')['@@locale'], 'pt');
    });

    test('both translation files have the same keys and placeholders, and none is empty', () {
      final en = _messages('en');
      final pt = _messages('pt');
      expect(pt.keys.toSet(), en.keys.toSet(), reason: 'a text exists in one language and not in the other');
      for (final k in en.keys) {
        expect(en[k]!.trim(), isNotEmpty, reason: 'en: $k is empty');
        expect(pt[k]!.trim(), isNotEmpty, reason: 'pt: $k is empty');
        expect(_placeholders(pt[k]!), _placeholders(en[k]!), reason: 'placeholders of $k differ');
      }
      expect(en.length, greaterThan(100));
    });

    test('Android 13+: the app declares English and Portuguese to the system (D-28 B)', () {
      final xml = File('android/app/src/main/res/xml/locales_config.xml').readAsStringSync();
      final declared = RegExp(r'<locale android:name="([^"]+)"').allMatches(xml).map((m) => m.group(1)).toSet();
      expect(declared, {'en', 'pt'});
      final manifest = File('android/app/src/main/AndroidManifest.xml').readAsStringSync();
      expect(manifest, contains('android:localeConfig="@xml/locales_config"'));
      // The manifest handles a language change itself: the screen is not
      // rebuilt and a running search goes on (story 6).
      expect(RegExp(r'android:configChanges="[^"]*\blocale\b').hasMatch(manifest), isTrue);
    });
  });

  group('ticket 02: search, errors and notices', () {
    test('plural: 1 video / 2 videos and 1 vídeo / 2 vídeos', () {
      expect(en.videoCount(1), '1 video');
      expect(en.videoCount(2), '2 videos');
      expect(pt.videoCount(1), '1 vídeo');
      expect(pt.videoCount(2), '2 vídeos');
      expect(en.channelCount(2), '2 channels');
      expect(pt.channelCount(2), '2 canais');
      expect(en.linksIgnored(1), '1 link ignored');
      expect(pt.linksIgnored(3), '3 links ignorados');
      expect(en.transcriptsCopied(1), '1 transcript copied.');
      expect(pt.transcriptsCopied(2), '2 transcrições copiadas.');
    });

    test('input line in both languages', () {
      final p = parseInput('https://google.com\nhttps://youtu.be/dQw4w9WgXcQ\n@mkbhd\n@other');
      expect('${en.recognizedText(p)} · ${en.ignoredText(p)}', 'Recognized: 1 video, 2 channels · 1 link ignored');
      expect('${pt.recognizedText(p)} · ${pt.ignoredText(p)}', 'Reconhecido: 1 vídeo, 2 canais · 1 link ignorado');
      final none = parseInput('hello');
      expect(en.recognizedText(none), 'No YouTube link recognized');
    });

    test('every failure reason has a sentence in each language', () {
      for (final r in FailureReason.values) {
        expect(en.failure(r), isNotEmpty);
        expect(pt.failure(r), isNot(en.failure(r)), reason: '$r');
      }
      expect(en.failure(FailureReason.membersOnly), 'Members only');
      expect(pt.failure(FailureReason.membersOnly), 'Exclusivo para membros');
    });

    test('job status in English', () {
      final j = Job(id: 'x', createdAt: DateTime(2026), input: '@a', settings: const JobSettings())
        ..items.addAll([
          JobItem('aaaaaaaaaaa', status: ItemStatus.ok),
          JobItem('bbbbbbbbbbb', status: ItemStatus.failed, reason: FailureReason.noCaptions),
          JobItem('ccccccccccc'),
        ]);
      j.state = JobState.running;
      expect(en.jobStatus(j, running: true), 'Processing 2 of 3');
      j
        ..state = JobState.paused
        ..pauseReason = FailureReason.network;
      expect(en.jobStatus(j, running: false), 'Paused: no connection · 2 of 3');
      j
        ..state = JobState.done
        ..pauseReason = null;
      expect(en.jobStatus(j, running: false), '1 ready · 1 failed');
      expect(pt.jobStatus(j, running: false), '1 pronto · 1 com falha');
    });

    test('the domain keeps codes and data: the runner saves notices, not sentences', () async {
      final dir = await Directory.systemTemp.createTemp('subshaul_l10n');
      addTearDown(() => dir.delete(recursive: true));
      final store = Store(dir);
      await store.init();
      final j = Job(id: 'n', createdAt: DateTime(2026), input: 'https://evil.com/x\ndQw4w9WgXcQ', settings: const JobSettings());
      await JobRunner(store: store, source: FakeSource(), gap: Duration.zero).run(j);
      expect(j.messages, [const Notice(NoticeCode.linkIgnored, ['https://evil.com/x'])]);
      final saved = File('${dir.path}/jobs/n.json').readAsStringSync();
      expect(saved, isNot(contains('ignorado')));
      expect(en.notice(j.messages.single), 'Link ignored (not from YouTube or incomplete): https://evil.com/x');
      expect(pt.notice(j.messages.single), 'Link ignorado (não é do YouTube ou está incompleto): https://evil.com/x');
    });

    test('Proteção: a link with fake placeholders shows literally', () async {
      const evil = r'https://evil.com/{count}%s{link}$1\n';
      final p = parseInput(evil);
      expect(p.invalid, [evil]);
      final n = Notice(NoticeCode.linkIgnored, [p.invalid.single]);
      expect(en.notice(n), 'Link ignored (not from YouTube or incomplete): $evil');
      expect(pt.notice(n), endsWith(': $evil'));
      // Saved and read back, it is still the same text.
      expect(Notice.fromJson(jsonDecode(jsonEncode(n.toJson()))), n);
    });

    test('story 29: notices saved by 1.4.1 show in the current language', () {
      Notice l(String s) => Notice.fromJson(s)!;
      final link = l('Link ignorado (não é do YouTube ou está incompleto): https://evil.com/x?a=1');
      expect(link, const Notice(NoticeCode.linkIgnored, ['https://evil.com/x?a=1']));
      expect(en.notice(link), 'Link ignored (not from YouTube or incomplete): https://evil.com/x?a=1');
      expect(en.notice(l('Chegou ao máximo de 25 vídeos. O resto ficou de fora.')),
          'Reached the maximum of 25 videos. The rest were skipped.');
      expect(en.notice(l('Playlist não encontrada ou privada: https://youtube.com/playlist?list=PLx')),
          'Playlist not found or private: https://youtube.com/playlist?list=PLx');
      expect(en.notice(l('Canal não encontrado ou privado: @nobody')), 'Channel not found or private: @nobody');
      expect(en.notice(l('Nenhum vídeo encontrado.')), 'No videos found.');
      expect(en.notice(l('Tradução para Japonês indisponível. Veio a legenda original')),
          'Translation to Japanese unavailable. Using the original captions');
      expect(en.notice(l('Sem legenda em Português (Brasil). Veio a de Inglês')),
          'No captions in Portuguese (Brazil). Using English instead');
      // A code 1.4.1 did not know was shown as the code itself.
      expect(en.notice(l('Sem legenda em Inglês. Veio a de xx-YY')), 'No captions in English. Using xx-YY instead');
      // An unknown sentence shows as it is.
      expect(en.notice(l('Alguma frase antiga')), 'Alguma frase antiga');
    });

    test('story 29: a job file of 1.4.1 opens with its notices and notes', () async {
      final dir = await Directory.systemTemp.createTemp('subshaul_old');
      addTearDown(() => dir.delete(recursive: true));
      final store = Store(dir);
      await store.init();
      File('${dir.path}/jobs/old.json').writeAsStringSync(jsonEncode({
        'v': 1,
        'id': 'old',
        'createdAt': '2026-11-01T10:00:00.000',
        'input': 'https://evil.com/x\nhttps://youtu.be/dQw4w9WgXcQ',
        'settings': {'language': 'ja', 'format': 'txt', 'timestamps': 'off', 'limit': 500},
        'state': 'done',
        'pauseReason': null,
        'messages': ['Link ignorado (não é do YouTube ou está incompleto): https://evil.com/x'],
        'items': [
          {
            'videoId': 'dQw4w9WgXcQ',
            'title': 'Never Gonna',
            'status': 'ok',
            'reason': null,
            'note': 'Sem legenda em Japonês. Veio a de Inglês',
            'fromCache': false,
          },
        ],
      }));
      final job = (await store.loadJobs()).single;
      expect(en.notice(job.messages.single), 'Link ignored (not from YouTube or incomplete): https://evil.com/x');
      expect(en.notice(job.items.single.note!), 'No captions in Japanese. Using English instead');
      expect(pt.notice(job.items.single.note!), 'Sem legenda em Japonês. Veio a de Inglês');
      // Saved again, it uses the new form and reads back the same.
      await store.saveJob(job);
      final again = (await store.loadJobs()).single;
      expect(again.messages, job.messages);
      expect(again.items.single.note, job.items.single.note);
    });

    test('a cache file of 1.4.1 with a sentence note still reads', () async {
      final dir = await Directory.systemTemp.createTemp('subshaul_cache');
      addTearDown(() => dir.delete(recursive: true));
      final store = Store(dir);
      await store.init();
      File('${dir.path}/cache/dQw4w9WgXcQ_pt.json').writeAsStringSync(jsonEncode({
        'transcript': _tr().toJson(),
        'note': 'Tradução para Português indisponível. Veio a legenda original',
        'cacheable': false,
      }));
      final o = await store.readCache('dQw4w9WgXcQ', 'pt');
      expect(o!.note, const Notice(NoticeCode.translationUnavailable, ['pt']));
    });
  });

  group('ticket 03: exported files', () {
    test('TXT and Markdown header in English and in Portuguese (D-30 A)', () {
      final t = _tr(translated: true);
      final txtEn = toTxt(t, TimestampMode.off, en.exportLabels);
      expect(txtEn, contains('Language: en (auto) (translated)'));
      final txtPt = toTxt(t, TimestampMode.off, pt.exportLabels);
      expect(txtPt, contains('Idioma: en (auto) (traduzida)'));
      final mdEn = toMarkdown(t, TimestampMode.both, en.exportLabels);
      expect(mdEn, contains('- Channel: Space Channel'));
      expect(mdEn, contains('- Video: <https://www.youtube.com/watch?v=dQw4w9WgXcQ>'));
      expect(mdEn, contains('- Language: en (auto) (translated)'));
      expect(mdEn, contains('## Text'));
      expect(mdEn, contains('## With timestamps'));
      final mdPt = toMarkdown(t, TimestampMode.both, pt.exportLabels);
      expect(mdPt, contains('- Canal: Space Channel'));
      expect(mdPt, contains('- Vídeo: <'));
      expect(mdPt, contains('- Idioma: en (auto) (traduzida)'));
      expect(mdPt, contains('## Texto'));
      expect(mdPt, contains('## Com timestamps'));
    });

    test('SRT, VTT and JSON are the same in both languages', () {
      final t = _tr();
      for (final f in [OutputFormat.srt, OutputFormat.vtt, OutputFormat.json]) {
        expect(render(t, f, TimestampMode.on, en.exportLabels), render(t, f, TimestampMode.on, pt.exportLabels));
      }
    });

    test('manifest columns and JSON keys are the same in both languages, as in 1.4.1', () {
      Archive zip(AppLocalizations l) => ZipDecoder().decodeBytes(buildZip([
            ExportEntry(videoId: 'dQw4w9WgXcQ', transcript: _tr()),
            const ExportEntry(videoId: 'zzzzzzzzzzz', reason: FailureReason.noCaptions),
          ], OutputFormat.json, TimestampMode.off, l.exportLabels).bytes);
      const cols = 'video_id,title,channel,url,status,reason,reason_text,track,file,note';
      for (final l in [en, pt]) {
        final a = zip(l);
        final csv = utf8.decode(a.findFile('manifest.csv')!.content as List<int>);
        expect(csv.replaceFirst('﻿', '').split('\n').first.trim(), cols);
        final m = jsonDecode(utf8.decode(a.findFile('manifest.json')!.content as List<int>)) as Map<String, dynamic>;
        expect(m.keys, ['format', 'timestamps', 'total', 'ok', 'videos']);
        expect((m['videos'] as List).first.keys, cols.split(','));
        final file = a.files.firstWhere((f) => f.name.startsWith('transcripts/'));
        final v = jsonDecode(utf8.decode(file.content as List<int>)) as Map<String, dynamic>;
        expect(v.keys, [
          'videoId', 'title', 'channel', 'url', 'language', 'languageName', //
          'isAutoGenerated', 'isTranslated', 'text', 'lines',
        ]);
        expect((v['lines'] as List).first.keys, ['start', 'duration', 'timestamp', 'text']);
        // Codes stay codes; only the human columns follow the language.
        expect(csv, contains('"noCaptions"'));
        expect(csv, contains(l.failure(FailureReason.noCaptions)));
      }
    });
  });

  group('ticket 04: caption languages and the default one', () {
