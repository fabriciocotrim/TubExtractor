    group('in the app', () {
      late Directory dir;
      late Store store;
      setUp(() async {
        dir = await Directory.systemTemp.createTemp('subshaul_lang');
        store = Store(dir);
        await store.init();
      });
      tearDown(() => dir.delete(recursive: true));

      Future<String> captionLang(Map<String, Object> prefs, String phone) async {
        SharedPreferences.setMockInitialValues(prefs);
        final p = await SharedPreferences.getInstance();
        final app = await AppState.start(store, FakeSource(), p, deviceLanguage: phone, gap: Duration.zero);
        expect(p.getString('language'), app.settings.language, reason: 'the choice is saved');
        return app.settings.language;
      }

      test('new install: the phone language', () async {
        expect(await captionLang({}, 'ja-JP'), 'ja');
      });

      test('new install with a phone language not on the list: English', () async {
        expect(await captionLang({}, 'qu-PE'), 'en');
      });

      test('a saved choice never changes', () async {
        expect(await captionLang({'language': 'fr'}, 'ja-JP'), 'fr');
        expect(await captionLang({'language': 'en'}, 'pt-BR'), 'en');
      });

      test('someone who used 1.4.1 without choosing keeps English', () async {
        expect(await captionLang({'theme': 'dark'}, 'pt-BR'), 'en');
      });

      test('someone with searches from 1.4.1 keeps English', () async {
        await store.saveJob(Job(id: 'old', createdAt: DateTime(2026), input: '@a', settings: const JobSettings())
          ..state = JobState.done);
        expect(await captionLang({}, 'pt-BR'), 'en');
      });

      test('the phone language changing later does not change it', () async {
        expect(await captionLang({}, 'ja-JP'), 'ja');
        final saved = (await SharedPreferences.getInstance()).getString('language')!;
        expect(await captionLang({'language': saved}, 'de-DE'), 'ja');
      });
    });
  });
