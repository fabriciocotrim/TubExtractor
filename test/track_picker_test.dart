import 'package:flutter_test/flutter_test.dart';
import 'package:subshaul/core/track_picker.dart';

CaptionTrack t(String code, {bool auto = false, bool translatable = true}) => CaptionTrack(
      baseUrl: 'https://www.youtube.com/api/timedtext?lang=$code${auto ? '&kind=asr' : ''}',
      languageCode: code,
      name: code,
      isAutoGenerated: auto,
      isTranslatable: translatable,
    );

void main() {
  test('sem faixas: null', () => expect(pickTrack([], 'en'), isNull));

  test('manual exata vence automática exata', () {
    final c = pickTrack([t('en', auto: true), t('en')], 'en')!;
    expect(c.track.isAutoGenerated, isFalse);
    expect(c.translateTo, isNull);
  });

  test('automática exata vence manual de idioma base', () {
    final c = pickTrack([t('pt-PT'), t('pt-BR', auto: true)], 'pt-BR')!;
    expect(c.track.languageCode, 'pt-BR');
  });

  test('idioma base: pt pega pt-BR', () {
    final c = pickTrack([t('en'), t('pt-BR')], 'pt')!;
    expect(c.track.languageCode, 'pt-BR');
    expect(c.translateTo, isNull);
  });

  test('sem o idioma: tradução da manual', () {
    final c = pickTrack([t('de', auto: true), t('en')], 'pt')!;
    expect(c.track.languageCode, 'en');
    expect(c.translateTo, 'pt');
  });

  test('sem idioma e sem tradução: original, manual primeiro', () {
    final c = pickTrack([t('de', auto: true, translatable: false), t('en', translatable: false)], 'pt')!;
    expect(c.track.languageCode, 'en');
    expect(c.translateTo, isNull);
  });
}
