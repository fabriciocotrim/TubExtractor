/// Portuguese words found in [text]. Links are data, not words.
List<String> _ptWords(String text) => RegExp(r'[\p{L}]+', unicode: true)
    .allMatches(text.replaceAll(RegExp(r'\S*(?:https?://|youtube\.com|youtu\.be)\S*'), ' '))
    .map((m) => m.group(0)!)
    .where((w) => _portuguese.contains(w.toLowerCase()) || RegExp('[ãõçáéíóúâêô]').hasMatch(w.toLowerCase()))
    .toList();

/// Every text on screen: visible text, tooltips and what a screen reader says.
List<String> _everything(WidgetTester tester) {
  final out = <String>[
    for (final e in find.byType(RichText).evaluate()) (e.widget as RichText).text.toPlainText(),
    for (final e in find.byType(EditableText).evaluate()) (e.widget as EditableText).controller.text,
    for (final e in find.byType(Tooltip).evaluate()) (e.widget as Tooltip).message ?? '',
  ];
  void visit(SemanticsNode n) {
    final d = n.getSemanticsData();
    out.addAll([d.label, d.value, d.hint, d.tooltip, d.increasedValue, d.decreasedValue]);
    n.visitChildren((c) {
      visit(c);
      return true;
    });
  }

  for (final view in tester.binding.renderViews) {
    final root = view.owner?.semanticsOwner?.rootSemanticsNode;
    if (root != null) visit(root);
  }
  return out.where((s) => s.trim().isNotEmpty).toList();
}

void _noPortuguese(WidgetTester tester, String where) {
  final leaks = [
    for (final t in _everything(tester))
      if (_ptWords(t).isNotEmpty) '"$t" (${_ptWords(t).join(', ')})',
  ];
  expect(leaks, isEmpty, reason: 'Portuguese on the English screen: $where');
}

/// English test data: titles and captions in English, one note, some failures.
class _EnglishSource extends FakeSource {
  _EnglishSource({this.delay = Duration.zero});
  final Duration delay;

  @override
  Future<FetchOutcome> fetchTranscript(String videoId, String preferredLanguage) async {
    if (delay > Duration.zero) await Future<void>.delayed(delay);
    final o = await super.fetchTranscript(videoId, preferredLanguage);
    return FetchOutcome(
      Transcript(
        videoId: videoId,
        title: 'Rocket landing $videoId',
        channel: 'Space Channel',
        languageCode: o.transcript.languageCode,
        languageName: 'English',
        isAutoGenerated: true,
        isTranslated: false,
        segments: const [
          Segment(0, 2000, 'Welcome back to the channel'),
          Segment(2000, 2000, 'Today the booster lands on the ship'),
          Segment(4000, 2000, 'Thanks for watching'),
        ],
      ),
      note: videoId.endsWith('1') ? const Notice(NoticeCode.otherLanguage, ['ja', 'en']) : null,
    );
  }
}

class _Picker extends FilePickerPlatform {
  Uint8List? saved;
  @override
  Future<Uri?> saveFile({
    required String fileName,
    required Uint8List bytes,
    required String mimeType,
    String? dialogTitle,
    String? initialDirectory,
    Function(FilePickerStatus)? onFileSaving,
    WindowsOptions windowsOptions = const WindowsOptions(),
    LinuxOptions linuxOptions = const LinuxOptions(),
    WebOptions webOptions = const WebOptions(),
  }) async {
    saved = bytes;
    return Uri.file('/tmp/$fileName');
  }
}

class _Intake extends ShareIntake {
  _Intake([this.shared]);

  /// A link shared to the app from another app (YouTube's Share button).
  final String? shared;
  @override
  Future<String?> initialText() async => shared;
  @override
  void listen(void Function(String text) onText) {}
  @override
  void stop() {}
}

/// Real time passes (files, isolates) and frames run until [done].
Future<void> _until(WidgetTester tester, bool Function() done, {String what = ''}) async {
  final sw = Stopwatch()..start();
  while (!done()) {
    if (sw.elapsed > const Duration(seconds: 15)) fail('timed out waiting: $what');
    await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 5)));
    await tester.pump(const Duration(milliseconds: 16));
  }
}

Future<void> _frames(WidgetTester tester, [int n = 30]) async {
  for (var i = 0; i < n; i++) {
    await tester.pump(const Duration(milliseconds: 16));
  }
}

