  group('fundo animado', () {
    Widget host({bool enabled = true}) => MediaQuery(
      data: const MediaQueryData(),
      child: Theme(
        data: crystalTheme(Brightness.dark),
        child: TickerMode(enabled: enabled, child: const Aurora()),
      ),
    );

    /// Frames the light asks for during ~1 s at 60 fps: time passes (timers
    /// run), then we look whether a frame callback waits, then draw. (Its
    /// clock is real time, so counting value changes would be flaky.)
    Future<int> count(WidgetTester tester) async {
      var n = 0;
      for (var i = 0; i < 60; i++) {
        await tester.binding.delayed(const Duration(milliseconds: 16));
        if (SchedulerBinding.instance.transientCallbackCount > 0) n++;
        await tester.pump();
      }
      return n;
    }

    testWidgets('repinta a ~20 quadros por segundo, não a cada quadro', (tester) async {
      await tester.pumpWidget(host());
      final n = await count(tester);
      expect(n, greaterThanOrEqualTo(10));
      expect(n, lessThanOrEqualTo(22));
    });

    testWidgets('para quando a tela não está visível', (tester) async {
      await tester.pumpWidget(host(enabled: false));
      expect(await count(tester), 0);
      await tester.pumpWidget(const SizedBox());
    });
  });
