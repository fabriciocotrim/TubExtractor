/// App with one finished job (one ready video), on a temp folder.
Future<(AppState, Job)> _appWithJob(WidgetTester tester) async {
  late Directory dir;
  late AppState app;
  late Job job;
  await tester.runAsync(() async {
    dir = await Directory.systemTemp.createTemp('subshaul_leves');
    final store = Store(dir);
    await store.init();
    SharedPreferences.setMockInitialValues({});
    app = await AppState.start(store, FakeSource(), await SharedPreferences.getInstance(), gap: Duration.zero);
    job = app.createJob('https://youtu.be/dQw4w9WgXcQ');
    while (job.state != JobState.done || app.isRunning(job)) {
      await Future<void>.delayed(const Duration(milliseconds: 5));
    }
  });
  addTearDown(() => dir.delete(recursive: true));
  return (app, job);
}

Transcript _long(Map<int, String> special) => Transcript(
  videoId: 'dQw4w9WgXcQ',
  title: 'Vídeo longo',
  channel: 'Canal',
  languageCode: 'pt',
  languageName: 'Português',
  isAutoGenerated: false,
  isTranslated: false,
  segments: [
    for (var i = 0; i < 3000; i++) Segment(i * 2000, 2000, special[i] ?? 'linha $i'),
  ],
);

Future<void> _frames(WidgetTester tester, [int n = 20]) async {
  for (var i = 0; i < n; i++) {
    await tester.pump(const Duration(milliseconds: 50));
  }
}

/// Save dialog that answers at once; [fail] makes it throw like a broken
/// platform. [saved] holds the ZIP bytes it got.
class _FakePicker extends FilePickerPlatform {
  bool fail = false;
  Uint8List? saved;

  @override
  Future<Uri?> saveFile({
    required String fileName,
    required Uint8List bytes,
    required String mimeType,
    String? dialogTitle,
    String? initialDirectory,
    Function(FilePickerStatus)? onFileSaving,
    WindowsOptions windowsOptions = const WindowsOptions(),
    LinuxOptions linuxOptions = const LinuxOptions(),
    WebOptions webOptions = const WebOptions(),
  }) async {
    saved = bytes;
    if (fail) throw Exception('falhou');
    return Uri.file('/tmp/$fileName');
  }
}

