  group('sair da busca no meio de uma ação não lança exceção', () {
    /// Opens the job screen over a home page, runs [act], closes the screen
    /// at once and lets the action finish after it closed. Real I/O (files,
    /// the ZIP isolate) needs real time, then a pump to run its continuation;
    /// [finished] says when the action reached its last step.
    Future<void> leaveDuring(
      WidgetTester tester,
      Future<void> Function() act,
      bool Function() finished,
    ) async {
      // Tall enough for the export sheet's button.
      tester.view
        ..physicalSize = const Size(800, 1600)
        ..devicePixelRatio = 1;
      addTearDown(tester.view.reset);
      final (app, job) = await _appWithJob(tester);
      await tester.pumpWidget(MaterialApp(
        theme: crystalTheme(Brightness.light),
        home: const Scaffold(body: Text('início')),
      ));
      tester.state<NavigatorState>(find.byType(Navigator)).push(
        MaterialPageRoute<void>(builder: (_) => JobScreen(app: app, job: job)),
      );
      await _frames(tester);

      await act();
      tester.state<NavigatorState>(find.byType(Navigator)).pop();
      await _frames(tester);
      expect(find.byType(JobScreen), findsNothing);

      for (var i = 0; i < 400 && !finished(); i++) {
        await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 10)));
        await tester.pump();
      }
      expect(finished(), isTrue, reason: 'a ação terminou com a tela já fechada');
      // The steps after the last platform call (message, spinner off).
      for (var i = 0; i < 5; i++) {
        await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 10)));
        await tester.pump();
      }
      expect(tester.takeException(), isNull);
    }

    /// Opens the export sheet from [button] and confirms with [confirm].
    Future<void> Function() export(WidgetTester tester, Finder button, String confirm) => () async {
      await tester.tap(button);
      await _frames(tester);
      await tester.tap(find.widgetWithText(FilledButton, confirm));
      await tester.pump();
      await tester.pump();
    };

