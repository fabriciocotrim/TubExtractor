/// Shared data types for TubExtractor.
library;

import 'languages.dart';

enum OutputFormat { txt, srt, vtt, md, json }

extension OutputFormatX on OutputFormat {
  String get extension => switch (this) {
        OutputFormat.txt => 'txt',
        OutputFormat.srt => 'srt',
        OutputFormat.vtt => 'vtt',
        OutputFormat.md => 'md',
        OutputFormat.json => 'json',
      };

  String get label => switch (this) {
        OutputFormat.txt => 'TXT',
        OutputFormat.srt => 'SRT',
        OutputFormat.vtt => 'VTT',
        OutputFormat.md => 'Markdown',
        OutputFormat.json => 'JSON',
      };

  /// SRT, VTT and JSON always carry timing; the timestamp option does not apply.
  bool get supportsTimestampOption => this == OutputFormat.txt || this == OutputFormat.md;
}

enum TimestampMode { off, on, both }


class Segment {
  const Segment(this.startMs, this.durationMs, this.text);
  final int startMs;
  final int durationMs;
  final String text;

  int get endMs => startMs + durationMs;

  Map<String, dynamic> toJson() => {'start': startMs, 'dur': durationMs, 'text': text};
  factory Segment.fromJson(Map<String, dynamic> j) =>
      Segment(j['start'] as int, j['dur'] as int, j['text'] as String);
}

class Transcript {
  const Transcript({
    required this.videoId,
    required this.title,
    required this.channel,
    required this.languageCode,
    required this.languageName,
    required this.isAutoGenerated,
    required this.isTranslated,
    required this.segments,
  });

  final String videoId;
  final String title;
  final String channel;
  final String languageCode;
  final String languageName;
  final bool isAutoGenerated;
  final bool isTranslated;
  final List<Segment> segments;

  String get url => 'https://www.youtube.com/watch?v=$videoId';

  String get plainText => segments.map((s) => s.text).join(' ').replaceAll(RegExp(r'\s+'), ' ').trim();

  Map<String, dynamic> toJson() => {
        'videoId': videoId,
        'title': title,
        'channel': channel,
        'languageCode': languageCode,
        'languageName': languageName,
        'isAutoGenerated': isAutoGenerated,
        'isTranslated': isTranslated,
        'segments': segments.map((s) => s.toJson()).toList(),
      };

  factory Transcript.fromJson(Map<String, dynamic> j) => Transcript(
        videoId: j['videoId'] as String,
        title: j['title'] as String,
        channel: j['channel'] as String,
        languageCode: j['languageCode'] as String,
        languageName: j['languageName'] as String,
        isAutoGenerated: j['isAutoGenerated'] as bool,
        isTranslated: j['isTranslated'] as bool? ?? false,
        segments: (j['segments'] as List).map((e) => Segment.fromJson(e as Map<String, dynamic>)).toList(),
      );
}

/// Short label of the caption track used, e.g. "en (auto)". [auto] and
/// [translated] are the words in the app's language.
String trackLabel(Transcript t, {required String auto, required String translated}) =>
    '${t.languageCode}${t.isAutoGenerated ? ' ($auto)' : ''}${t.isTranslated ? ' ($translated)' : ''}';

/// Why a video has no transcript. The screen turns it into a sentence; the
/// manifest also writes its [FailureReasonX.code].
enum FailureReason {
  noCaptions,
  membersOnly,
  ageRestricted,
  unavailable,
  rateLimited,
  network,
  unknown,
}

extension FailureReasonX on FailureReason {
  String get code => name;
}

/// What a notice says, as a code. The screen writes the sentence in the app's
/// language, so a saved job shows its notices in whatever language the app
/// has when it opens.
enum NoticeCode {
  /// args: [the ignored link]
  linkIgnored,

  /// args: [the limit]
  limitReached,

  /// args: [the link]
  playlistNotFound,

  /// args: [the link]
  channelNotFound,
  noVideos,

  /// Caption note. args: [language code asked for]
  translationUnavailable,

  /// Caption note. args: [language code asked for, language code that came]
  otherLanguage,

  /// A sentence saved by an older version that is not recognized: shown as
  /// it is. args: [the sentence]
  text,
}

/// A notice about a job (bad link, limit reached…) or about one video's
/// captions (fallback track). Text from outside (links) goes in [args] and is
/// shown as plain text.
class Notice {
  const Notice(this.code, [this.args = const []]);
  final NoticeCode code;
  final List<String> args;

  Map<String, dynamic> toJson() => {'code': code.name, 'args': args};

  /// Reads a saved notice: the current form, or a sentence saved by 1.4.1.
  static Notice? fromJson(Object? j) {
    if (j is String) return Notice.legacy(j);
    if (j is! Map) return null;
    final code = NoticeCode.values.asNameMap()[j['code']];
    final args = (j['args'] as List? ?? const []).map((a) => '$a').toList();
    if (code == null) return Notice(NoticeCode.text, [args.join(' ')]);
    return Notice(code, args);
  }

  /// Version 1.4.1 saved finished Portuguese sentences. The known ones turn
  /// back into codes (with the link or language they carried); any other
  /// sentence stays as it is.
  factory Notice.legacy(String s) {
    for (final (re, code, names) in _legacy) {
      final m = re.firstMatch(s);
      if (m == null) continue;
      final args = [for (var i = 1; i <= m.groupCount; i++) m.group(i)!];
      return Notice(code, names ? args.map(_codeOfPtName).toList() : args);
    }
    return Notice(NoticeCode.text, [s]);
  }

  @override
  bool operator ==(Object other) =>
      other is Notice && other.code == code && _sameArgs(other.args);

  bool _sameArgs(List<String> o) {
    if (o.length != args.length) return false;
    for (var i = 0; i < args.length; i++) {
      if (args[i] != o[i]) return false;
    }
    return true;
  }

  @override
  int get hashCode => Object.hash(code, Object.hashAll(args));

  @override
  String toString() => 'Notice(${code.name}, $args)';
}

/// The Portuguese sentences of version 1.4.1 (job_runner.dart and
/// youtube_client.dart), as regular expressions over the saved text. The
/// bool says the captured parts are language names, not links.
final _legacy = <(RegExp, NoticeCode, bool)>[
  (RegExp(r'^Link ignorado \(não é do YouTube ou está incompleto\): (.*)$', dotAll: true), NoticeCode.linkIgnored, false),
  (RegExp(r'^Chegou ao máximo de (\d+) vídeos\. O resto ficou de fora\.$'), NoticeCode.limitReached, false),
  (RegExp(r'^Playlist não encontrada ou privada: (.*)$', dotAll: true), NoticeCode.playlistNotFound, false),
  (RegExp(r'^Canal não encontrado ou privado: (.*)$', dotAll: true), NoticeCode.channelNotFound, false),
  (RegExp(r'^Nenhum vídeo encontrado\.$'), NoticeCode.noVideos, false),
  (RegExp(r'^Tradução para (.+) indisponível\. Veio a legenda original$'), NoticeCode.translationUnavailable, true),
  (RegExp(r'^Sem legenda em (.+)\. Veio a de (.+)$'), NoticeCode.otherLanguage, true),
];

/// Language code for a Portuguese language name saved by 1.4.1. A name not
/// in the list was a code already (1.4.1 showed unknown codes as they were).
String _codeOfPtName(String name) {
  for (final l in languages) {
    if (l.pt == name) return l.code;
  }
  return name;
}

class TranscriptException implements Exception {
  TranscriptException(this.reason, [this.detail, this.title]);
  final FailureReason reason;
  final String? detail;

  /// Video title, when YouTube returned it before the failure.
  final String? title;
  @override
  String toString() => 'TranscriptException(${reason.code}${detail == null ? '' : ': $detail'})';
}
