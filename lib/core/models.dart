/// Shared data types for TubExtractor.
library;

enum OutputFormat { txt, srt, vtt, md, json }

extension OutputFormatX on OutputFormat {
  String get extension => switch (this) {
        OutputFormat.txt => 'txt',
        OutputFormat.srt => 'srt',
        OutputFormat.vtt => 'vtt',
        OutputFormat.md => 'md',
        OutputFormat.json => 'json',
      };

  String get label => switch (this) {
        OutputFormat.txt => 'TXT',
        OutputFormat.srt => 'SRT',
        OutputFormat.vtt => 'VTT',
        OutputFormat.md => 'Markdown',
        OutputFormat.json => 'JSON',
      };

  /// SRT, VTT and JSON always carry timing; the timestamp option does not apply.
  bool get supportsTimestampOption => this == OutputFormat.txt || this == OutputFormat.md;
}

enum TimestampMode { off, on, both }

extension TimestampModeX on TimestampMode {
  String get label => switch (this) {
        TimestampMode.off => 'Off',
        TimestampMode.on => 'On',
        TimestampMode.both => 'Both',
      };
}

class Segment {
  const Segment(this.startMs, this.durationMs, this.text);
  final int startMs;
  final int durationMs;
  final String text;

  int get endMs => startMs + durationMs;

  Map<String, dynamic> toJson() => {'start': startMs, 'dur': durationMs, 'text': text};
  factory Segment.fromJson(Map<String, dynamic> j) =>
      Segment(j['start'] as int, j['dur'] as int, j['text'] as String);
}

class Transcript {
  const Transcript({
    required this.videoId,
    required this.title,
    required this.channel,
    required this.languageCode,
    required this.languageName,
    required this.isAutoGenerated,
    required this.isTranslated,
    required this.segments,
  });

  final String videoId;
  final String title;
  final String channel;
  final String languageCode;
  final String languageName;
  final bool isAutoGenerated;
  final bool isTranslated;
  final List<Segment> segments;

  String get url => 'https://www.youtube.com/watch?v=$videoId';

  /// Short label of the caption track used, e.g. "en (auto)".
  String get trackLabel =>
      '$languageCode${isAutoGenerated ? ' (auto)' : ''}${isTranslated ? ' (traduzida)' : ''}';

  String get plainText => segments.map((s) => s.text).join(' ').replaceAll(RegExp(r'\s+'), ' ').trim();

  Map<String, dynamic> toJson() => {
        'videoId': videoId,
        'title': title,
        'channel': channel,
        'languageCode': languageCode,
        'languageName': languageName,
        'isAutoGenerated': isAutoGenerated,
        'isTranslated': isTranslated,
        'segments': segments.map((s) => s.toJson()).toList(),
      };

  factory Transcript.fromJson(Map<String, dynamic> j) => Transcript(
        videoId: j['videoId'] as String,
        title: j['title'] as String,
        channel: j['channel'] as String,
        languageCode: j['languageCode'] as String,
        languageName: j['languageName'] as String,
        isAutoGenerated: j['isAutoGenerated'] as bool,
        isTranslated: j['isTranslated'] as bool? ?? false,
        segments: (j['segments'] as List).map((e) => Segment.fromJson(e as Map<String, dynamic>)).toList(),
      );
}

/// Why a video has no transcript. Shown to the user and written to the manifest.
enum FailureReason {
  noCaptions,
  membersOnly,
  ageRestricted,
  unavailable,
  rateLimited,
  network,
  unknown,
}

extension FailureReasonX on FailureReason {
  String get code => name;

  String get message => switch (this) {
        FailureReason.noCaptions => 'Vídeo sem legendas',
        FailureReason.membersOnly => 'Exclusivo para membros',
        FailureReason.ageRestricted => 'Restrito por idade (o YouTube exige login)',
        FailureReason.unavailable => 'Privado, removido ou indisponível',
        FailureReason.rateLimited => 'O YouTube bloqueou por excesso de pedidos. Tente mais tarde',
        FailureReason.network => 'Sem conexão',
        FailureReason.unknown => 'Erro inesperado',
      };
}

class TranscriptException implements Exception {
  TranscriptException(this.reason, [this.detail, this.title]);
  final FailureReason reason;
  final String? detail;

  /// Video title, when YouTube returned it before the failure.
  final String? title;
  @override
  String toString() => 'TranscriptException(${reason.code}${detail == null ? '' : ': $detail'})';
}
