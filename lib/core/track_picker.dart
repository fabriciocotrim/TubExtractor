/// Chooses which caption track to download for a preferred language.
library;

class CaptionTrack {
  const CaptionTrack({
    required this.baseUrl,
    required this.languageCode,
    required this.name,
    required this.isAutoGenerated,
    required this.isTranslatable,
  });
  final String baseUrl;
  final String languageCode;
  final String name;
  final bool isAutoGenerated;
  final bool isTranslatable;
}

class TrackChoice {
  const TrackChoice(this.track, {this.translateTo});
  final CaptionTrack track;

  /// When set, ask YouTube to machine-translate [track] into this language.
  final String? translateTo;
}

String baseLang(String code) => code.toLowerCase().split(RegExp('[-_]')).first;

/// Preference order (see spec):
/// manual exact → auto exact → manual same base → auto same base →
/// translation of the best track → original (manual first).
TrackChoice? pickTrack(List<CaptionTrack> tracks, String preferred) {
  if (tracks.isEmpty) return null;
  final p = preferred.toLowerCase();
  final pb = baseLang(p);
  final manual = tracks.where((t) => !t.isAutoGenerated).toList();
  final auto = tracks.where((t) => t.isAutoGenerated).toList();

  CaptionTrack? find(List<CaptionTrack> list, bool Function(CaptionTrack) f) {
    for (final t in list) {
      if (f(t)) return t;
    }
    return null;
  }

  final exact = find(manual, (t) => t.languageCode.toLowerCase() == p) ??
      find(auto, (t) => t.languageCode.toLowerCase() == p) ??
      find(manual, (t) => baseLang(t.languageCode) == pb) ??
      find(auto, (t) => baseLang(t.languageCode) == pb);
  if (exact != null) return TrackChoice(exact);

  final original = manual.isNotEmpty ? manual.first : auto.first;
  // Prefer translating a manual track; it gives better text than auto captions.
  final translatable = find(manual, (t) => t.isTranslatable) ?? find(auto, (t) => t.isTranslatable);
  if (translatable != null) return TrackChoice(translatable, translateTo: preferred);
  return TrackChoice(original);
}
